export function hasPhosphorIcon(name?: string | null) {
  return Boolean(name && ICONS[name]);
}

export default function CategoryPhosphorIcon({
  name,
  size = 22,
  className,
}: {
  name?: string | null;
  size?: number;
  className?: string;
}) {
  if (isBrandIcon(name)) {
    return <BrandMark name={name} size={size} className={className} />;
  }

  const PhosphorIcon = ICONS[name || ''] || Tag;

  return (
    <PhosphorIcon
      aria-hidden="true"
      className={className}
      size={size}
      weight="duotone"
    />
  );
}
